// Демо-каталог: категории, товары с ценами (сум), характеристиками и описанием.

type nut struct{ kcal, protein, fat, carbs float64 }

type demoProduct struct {
	name, brand, unit string // unit: шт, кг, л, уп
	price             int
	nut               *nut
	extra             map[string]string // composition, shelf_life, storage, country, volume, manufacturer
	desc              string
}

type demoCategory struct {
	name     string
	children []demoCategory
	products []demoProduct
	// Общие для категории характеристики и описание.
	storage, shelfLife, desc string
}

func n(kcal, p, f, c float64) *nut { return &nut{kcal, p, f, c} }

func p(name, brand, unit string, price int, nu *nut, extra ...string) demoProduct {
	d := demoProduct{name: name, brand: brand, unit: unit, price: price, nut: nu, extra: map[string]string{}}
	for i := 0; i+1 < len(extra); i += 2 {
		if extra[i] == "desc" {
			d.desc = extra[i+1]
			continue
		}
		d.extra[extra[i]] = extra[i+1]
	}
	return d
}

