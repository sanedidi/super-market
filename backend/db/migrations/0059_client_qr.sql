-- QR покупателя для продажи в долг (Figma «Долги · QR-код покупателя вместо
-- номера телефона»).
--
-- Покупатель показывает в приложении «Мой QR-код», касса сканирует — номер
-- диктовать и подтверждать кодом не нужно. QR живой: одноразовая часть
-- меняется каждые 30 секунд (как в Google Authenticator) и считается в
-- телефоне из секрета, поэтому работает без интернета. Касса проверяет её на
-- сервере — фото или скриншот чужого QR через минуту не подходит.
--
-- В QR только цифры: «99» + qr_id (10 цифр) + код (8 цифр). Цифры сканер
-- кассы печатает одинаково при любой раскладке клавиатуры.
CREATE TABLE client_qr (
    user_id    uuid        PRIMARY KEY REFERENCES users (id),
    -- Публичный номер QR: по нему касса без связи находит покупателя в своём
    -- каталоге. Номера телефона в QR нет.
    qr_id      text        NOT NULL UNIQUE CHECK (qr_id ~ '^[1-9][0-9]{9}$'),
    secret     bytea       NOT NULL CHECK (length(secret) = 32),
    created_at timestamptz NOT NULL DEFAULT now()
);
